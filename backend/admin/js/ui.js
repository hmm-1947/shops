export function icon(name) {
  const s = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  s.setAttribute('viewBox', '0 0 24 24');
  s.setAttribute('class', 'ico');
  s.setAttribute('aria-hidden', 'true');
  const p = document.createElementNS('http://www.w3.org/2000/svg', 'path');
  p.setAttribute('d', ICONS[name]);
  s.append(p);
  return s;
}

const currentTheme = () => (document.documentElement.getAttribute('data-theme') === 'light' ? 'light' : 'dark');

export function themeToggle(extra = '') {
  const btn = h('button', { class: ('btn ghost theme-toggle ' + extra).trim(), type: 'button' });
  const paint = () => {
    const next = currentTheme() === 'light' ? 'dark' : 'light';
    const text = next === 'light' ? 'Light mode' : 'Dark mode';
    btn.title = text;
    btn.setAttribute('aria-label', 'Switch to ' + text.toLowerCase());
    btn.replaceChildren(icon(next === 'light' ? 'sun' : 'moon'), h('span', { class: 'lbl' }, text));
  };
  btn.addEventListener('click', () => {
    const next = currentTheme() === 'light' ? 'dark' : 'light';
    document.documentElement.setAttribute('data-theme', next);
    try {
      localStorage.setItem('wm_theme', next);
    } catch {}
    paint();
  });
  paint();
  return btn;
}
